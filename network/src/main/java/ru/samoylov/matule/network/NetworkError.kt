package ru.samoylov.matule.network

/**
 * Типы ошибок сетевого слоя.
 * Перечисление не зависит от конкретной библиотеки: при замене Retrofit
 * на другую реализацию набор ошибок остаётся прежним.
 */
enum class NetworkError {
    /** Нет соединения с интернетом */
    NO_CONNECTION,

    /** Истекло время ожидания ответа */
    TIMEOUT,

    /** Неверный логин или пароль, истёкший токен (401, 403) */
    UNAUTHORIZED,

    /** Запрошенный ресурс не найден (404) */
    NOT_FOUND,

    /** Данные запроса не прошли проверку на сервере (400, 422) */
    VALIDATION,

    /** Внутренняя ошибка сервера (5xx) */
    SERVER,

    /** Ответ сервера не удалось разобрать */
    PARSING,

    /** Прочие непредвиденные ошибки */
    UNKNOWN
}
